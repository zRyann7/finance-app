import { createClient } from "@supabase/supabase-js";

const supabaseUrl = import.meta.env.VITE_SUPABASE_URL || "";
const supabaseAnonKey = import.meta.env.VITE_SUPABASE_ANON_KEY || "";

export const supabase = createClient(supabaseUrl, supabaseAnonKey);

// O login é feito pelo backend, então este cliente nunca recebe a sessão e age como "anon".
// As policies do Storage exigem o papel "authenticated": para enviar arquivos, criamos um
// cliente que repassa o JWT do usuário no header Authorization.
export function createSupabaseWithToken(accessToken) {
  return createClient(supabaseUrl, supabaseAnonKey, {
    auth: {
      persistSession: false,
      autoRefreshToken: false,
      detectSessionInUrl: false,
    },
    global: {
      headers: { Authorization: `Bearer ${accessToken}` },
    },
  });
}
